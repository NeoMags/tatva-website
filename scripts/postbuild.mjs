/**
 * Runs after `astro build`. Writes dist/_headers for Cloudflare Pages:
 * security headers and a Content-Security-Policy that allows only this site's own
 * files, plus the exact SHA-256 hash of every inline script Astro emitted (so no
 * 'unsafe-inline' for scripts). Recomputed on every build, so hashes never go stale.
 *
 * Usage: node scripts/postbuild.mjs [distDir]
 */
import { createHash } from "node:crypto";
import { readFileSync, readdirSync, statSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const dist = process.argv[2] ?? "dist";

function* htmlFiles(dir) {
  for (const name of readdirSync(dir)) {
    const p = join(dir, name);
    if (statSync(p).isDirectory()) yield* htmlFiles(p);
    else if (p.endsWith(".html")) yield p;
  }
}

// Inline <script> elements without src, excluding data blocks (application/json).
const INLINE = /<script(?![^>]*\bsrc=)([^>]*)>([\s\S]*?)<\/script>/g;
const hashes = new Set();
let pages = 0;
for (const file of htmlFiles(dist)) {
  pages++;
  const html = readFileSync(file, "utf8");
  for (const [, attrs, body] of html.matchAll(INLINE)) {
    if (/type\s*=\s*"application\/(ld\+)?json"/.test(attrs)) continue;
    hashes.add(`'sha256-${createHash("sha256").update(body, "utf8").digest("base64")}'`);
  }
}

const TURNSTILE = "https://challenges.cloudflare.com";
const csp = [
  "default-src 'self'",
  `script-src 'self' ${[...hashes].sort().join(" ")} ${TURNSTILE}`,
  // style attributes carry layout variables (--x, --n …); they need 'unsafe-inline'.
  "style-src 'self' 'unsafe-inline'",
  "img-src 'self' data: blob:",
  "font-src 'self'",
  "media-src 'self' blob:",
  "connect-src 'self'",
  `frame-src ${TURNSTILE}`,
  "object-src 'none'",
  "base-uri 'self'",
  "form-action 'self'",
  "frame-ancestors 'none'",
  "upgrade-insecure-requests",
].join("; ");

const headers = `# Generated by scripts/postbuild.mjs — do not edit by hand.
/*
  Content-Security-Policy: ${csp}
  X-Content-Type-Options: nosniff
  Referrer-Policy: strict-origin-when-cross-origin
  Permissions-Policy: microphone=(self), geolocation=(self), camera=(), payment=(), usb=(), interest-cohort=()
  Cross-Origin-Opener-Policy: same-origin
  Strict-Transport-Security: max-age=31536000; includeSubDomains

/_astro/*
  Cache-Control: public, max-age=31536000, immutable

/api/*
  Cache-Control: no-store
`;

writeFileSync(join(dist, "_headers"), headers);
console.log(`postbuild: _headers written (${pages} pages, ${hashes.size} inline script hashes)`);
